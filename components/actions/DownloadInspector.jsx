import React, { useState } from 'react';
import { Box, Text, Button, Icon, Badge } from '@adminjs/design-system';
import { useNotice } from 'adminjs';

const DownloadInspector = (props) => {
    const { record } = props;
    const sendNotice = useNotice();
    const [copied, setCopied] = useState(false);

    if (!record || !record.params) {
        return (
            <Box p="xl" textAlign="center">
                <Text variant="h4">No record data found.</Text>
            </Box>
        );
    }

    const fileId = record.params._id || record.id;
    const fileName = record.params.name || 'Mod File';
    const fileVersion = record.params.version || '1.0';
    const fileSize = record.params.fileSize || 'N/A';
    const externalUrl = record.params.externalDownloadUrl || '';
    const fileKey = record.params.fileKey || '';
    const directUrl = record.params.directDownloadUrl || '';
    const isMultiPart = record.params.isMultiPart === true || record.params.isMultiPart === 'true';

    // The primary valid download endpoint generated by the server
    const primaryDownloadUrl = `${window.location.origin}/download-file/${fileId}`;

    const handleCopy = (urlToCopy) => {
        if (!urlToCopy) return;
        navigator.clipboard.writeText(urlToCopy).then(() => {
            setCopied(true);
            sendNotice({ message: 'Download URL copied to clipboard!', type: 'success' });
            setTimeout(() => setCopied(false), 3000);
        }).catch(() => {
            sendNotice({ message: 'Failed to copy URL to clipboard.', type: 'error' });
        });
    };

    const handleStartDownload = (targetUrl) => {
        sendNotice({ message: 'Initiating file download in new tab...', type: 'info' });
        window.open(targetUrl || primaryDownloadUrl, '_blank');
    };

    const handleBack = () => {
        if (window.history.length > 1) {
            window.history.back();
        } else {
            window.location.href = `/admin/resources/File/records/${fileId}/show`;
        }
    };

    return (
        <Box p="xxl" style={{ maxWidth: '820px', margin: '0 auto', fontFamily: "'Poppins', sans-serif" }}>
            <Box
                p="xl"
                style={{
                    backgroundColor: '#161924',
                    border: '1px solid rgba(255, 215, 0, 0.35)',
                    borderRadius: '16px',
                    boxShadow: '0 12px 35px rgba(0, 0, 0, 0.65)'
                }}
            >
                {/* Header */}
                <Box flex justifyContent="space-between" alignItems="center" mb="xl">
                    <Box>
                        <Text variant="h3" style={{ color: '#FFD700', margin: 0, fontWeight: 700 }}>
                            <Icon icon="Download" style={{ marginRight: '10px' }} />
                            Download Inspector
                        </Text>
                        <Text style={{ color: '#aaa', fontSize: '13px', marginTop: '4px' }}>
                            Inspect, verify, copy or test download URLs safely without unwanted downloads
                        </Text>
                    </Box>
                    <Button variant="light" size="sm" onClick={handleBack} style={{ cursor: 'pointer' }}>
                        <Icon icon="ArrowLeft" style={{ marginRight: '6px' }} />
                        Back to Mod
                    </Button>
                </Box>

                {/* Mod Meta Snapshot */}
                <Box
                    p="lg"
                    mb="xl"
                    style={{
                        backgroundColor: '#0e1017',
                        borderRadius: '10px',
                        border: '1px solid rgba(255, 255, 255, 0.08)'
                    }}
                >
                    <Box flex justifyContent="space-between" alignItems="center" flexWrap="wrap" style={{ gap: '10px' }}>
                        <div>
                            <Text style={{ color: '#fff', fontSize: '16px', fontWeight: 600 }}>{fileName}</Text>
                            <Text style={{ color: '#888', fontSize: '12px' }}>ID: {fileId}</Text>
                        </div>
                        <Box flex style={{ gap: '8px' }}>
                            <Badge variant="primary" style={{ backgroundColor: '#2a2f45', color: '#c0c6e0' }}>
                                v{fileVersion}
                            </Badge>
                            <Badge variant="info" style={{ backgroundColor: '#1d3557', color: '#64b5f6' }}>
                                Size: {fileSize}
                            </Badge>
                            {isMultiPart && (
                                <Badge variant="warning" style={{ backgroundColor: '#4a3800', color: '#ffd54f' }}>
                                    Multi-Part File
                                </Badge>
                            )}
                        </Box>
                    </Box>
                </Box>

                {/* Primary Valid URL Box */}
                <Box mb="xl">
                    <Text style={{ color: '#FFD700', fontWeight: 600, fontSize: '13px', textTransform: 'uppercase', letterSpacing: '0.5px', marginBottom: '8px' }}>
                        Primary Verified Download Route:
                    </Text>
                    <Box
                        p="md"
                        style={{
                            backgroundColor: '#0b0c10',
                            border: '1px solid #333',
                            borderRadius: '8px',
                            display: 'flex',
                            alignItems: 'center',
                            justifyContent: 'space-between',
                            gap: '12px'
                        }}
                    >
                        <Text style={{ color: '#00e5ff', fontFamily: 'monospace', fontSize: '13px', wordBreak: 'break-all' }}>
                            {primaryDownloadUrl}
                        </Text>
                        <Box flex style={{ gap: '8px', flexShrink: 0 }}>
                            <Button
                                size="sm"
                                variant="secondary"
                                onClick={() => handleCopy(primaryDownloadUrl)}
                                style={{ cursor: 'pointer', background: copied ? '#2ecc71' : undefined }}
                            >
                                <Icon icon={copied ? 'Check' : 'Copy'} style={{ marginRight: '6px' }} />
                                {copied ? 'Copied' : 'Copy URL'}
                            </Button>
                            <Button
                                size="sm"
                                variant="primary"
                                onClick={() => handleStartDownload(primaryDownloadUrl)}
                                style={{ backgroundColor: '#FFD700', color: '#000', fontWeight: 600, cursor: 'pointer' }}
                            >
                                <Icon icon="ExternalLink" style={{ marginRight: '6px' }} />
                                Test Download
                            </Button>
                        </Box>
                    </Box>
                </Box>

                {/* Additional Endpoints & Cloud Storage Info */}
                <Box mb="lg">
                    {externalUrl && (
                        <Box mb="md">
                            <Text style={{ color: '#bbb', fontSize: '12px', fontWeight: 600, marginBottom: '4px' }}>
                                External Cloud Mirror URL:
                            </Text>
                            <Box p="sm" style={{ backgroundColor: '#0b0c10', border: '1px solid #222', borderRadius: '6px', display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                                <Text style={{ color: '#ccc', fontSize: '12px', fontFamily: 'monospace', wordBreak: 'break-all' }}>{externalUrl}</Text>
                                <Button size="sm" variant="text" onClick={() => handleCopy(externalUrl)} style={{ cursor: 'pointer', color: '#FFD700' }}>
                                    <Icon icon="Copy" />
                                </Button>
                            </Box>
                        </Box>
                    )}

                    {fileKey && (
                        <Box mb="md">
                            <Text style={{ color: '#bbb', fontSize: '12px', fontWeight: 600, marginBottom: '4px' }}>
                                Backblaze B2 Storage Key:
                            </Text>
                            <Box p="sm" style={{ backgroundColor: '#0b0c10', border: '1px solid #222', borderRadius: '6px', display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                                <Text style={{ color: '#aaa', fontSize: '12px', fontFamily: 'monospace', wordBreak: 'break-all' }}>{fileKey}</Text>
                                <Button size="sm" variant="text" onClick={() => handleCopy(fileKey)} style={{ cursor: 'pointer', color: '#FFD700' }}>
                                    <Icon icon="Copy" />
                                </Button>
                            </Box>
                        </Box>
                    )}

                    {directUrl && (
                        <Box mb="md">
                            <Text style={{ color: '#bbb', fontSize: '12px', fontWeight: 600, marginBottom: '4px' }}>
                                Direct CDN / Cloudflare Passthrough:
                            </Text>
                            <Box p="sm" style={{ backgroundColor: '#0b0c10', border: '1px solid #222', borderRadius: '6px', display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                                <Text style={{ color: '#2ecc71', fontSize: '12px', fontFamily: 'monospace', wordBreak: 'break-all' }}>{directUrl}</Text>
                                <Button size="sm" variant="text" onClick={() => handleCopy(directUrl)} style={{ cursor: 'pointer', color: '#FFD700' }}>
                                    <Icon icon="Copy" />
                                </Button>
                            </Box>
                        </Box>
                    )}
                </Box>

                {/* Footer Buttons */}
                <Box flex justifyContent="flex-end" style={{ gap: '10px' }} mt="xl" pt="lg" borderTop="1px solid rgba(255, 255, 255, 0.08)">
                    <Button variant="light" onClick={handleBack} style={{ cursor: 'pointer' }}>
                        Done
                    </Button>
                    <Button
                        variant="primary"
                        onClick={() => handleStartDownload(primaryDownloadUrl)}
                        style={{ backgroundColor: '#FFD700', color: '#000', fontWeight: 600, cursor: 'pointer' }}
                    >
                        <Icon icon="Download" style={{ marginRight: '6px' }} />
                        Launch Download
                    </Button>
                </Box>
            </Box>
        </Box>
    );
};

export default DownloadInspector;
